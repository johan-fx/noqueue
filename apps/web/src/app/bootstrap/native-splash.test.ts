import { afterEach, beforeEach, expect, it, vi } from 'vitest'
const mock = vi.hoisted(() => ({ hide: vi.fn(), native: true }))
vi.mock('@capacitor/splash-screen', () => ({ SplashScreen: { hide: mock.hide } }))
vi.mock('./runtime', () => ({ detectRuntime: () => mock.native ? 'native' : 'web' }))
let splash: typeof import('./native-splash')
beforeEach(async () => {
  vi.resetModules(); vi.useFakeTimers()
  mock.native = true; mock.hide.mockReset().mockResolvedValue(undefined)
  document.body.innerHTML = '<div id="root"></div>'
  splash = await import('./native-splash')
})
afterEach(() => { vi.useRealTimers(); document.body.innerHTML = '' })
it('retains splash while startup is pending, with no minimum dwell once ready', async () => {
  splash.startNativeSplashRecovery()
  await vi.advanceTimersByTimeAsync(1000)
  expect(mock.hide).not.toHaveBeenCalled()
  splash.finishNativeStartup()
  expect(mock.hide).toHaveBeenCalledExactlyOnceWith({ fadeOutDuration: 150 })
  await vi.advanceTimersByTimeAsync(30000)
  expect(document.getElementById('noqueue-startup-recovery')).toBeNull()
})
it('dismisses just once across StrictMode, navigation and resume', () => {
  splash.startNativeSplashRecovery()
  splash.finishNativeStartup(); splash.finishNativeStartup()
  splash.startNativeSplashRecovery()
  expect(mock.hide).toHaveBeenCalledOnce()
  expect(vi.getTimerCount()).toBe(0)
})
it('does not touch the web UI or native bridge on web', async () => {
  mock.native = false
  splash.startNativeSplashRecovery(); splash.finishNativeStartup()
  await vi.advanceTimersByTimeAsync(30000)
  expect(mock.hide).not.toHaveBeenCalled()
  expect(document.getElementById('noqueue-startup-recovery')).toBeNull()
})
it('reveals a manual retry after a stuck startup, preserving saved data', async () => {
  localStorage.setItem('test-vault', 'preserve')
  splash.startNativeSplashRecovery()
  await vi.advanceTimersByTimeAsync(19999)
  expect(mock.hide).not.toHaveBeenCalled()
  await vi.advanceTimersByTimeAsync(1)
  expect(mock.hide).toHaveBeenCalledOnce()
  expect(document.getElementById('noqueue-startup-recovery')?.textContent).toContain('Volver a intentar')
  expect(document.getElementById('root')?.inert).toBe(true)
  expect(localStorage.getItem('test-vault')).toBe('preserve')
  // Late recovery removes the emergency UI instead of stranding it over React.
  splash.finishNativeStartup()
  expect(document.getElementById('noqueue-startup-recovery')).toBeNull()
  expect(document.getElementById('root')?.inert).toBe(false)
  expect(mock.hide).toHaveBeenCalledOnce()
  localStorage.removeItem('test-vault')
})
it('tolerates unavailable plugins and lets a later ready signal retry dismissal', async () => {
  mock.hide.mockRejectedValueOnce(new Error('not implemented'))
  splash.finishNativeStartup()
  await Promise.resolve(); await Promise.resolve()
  splash.finishNativeStartup()
  expect(mock.hide).toHaveBeenCalledTimes(2)
})
