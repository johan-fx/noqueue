import { beforeEach, expect, it, vi } from 'vitest'
const mock = vi.hoisted(() => ({ read: vi.fn(), write: vi.fn() }))
vi.mock('@capacitor/core', () => ({ registerPlugin: () => mock }))
beforeEach(() => { vi.resetModules(); mock.read.mockReset().mockResolvedValue({ value: null }); mock.write.mockReset().mockResolvedValue(undefined) })
const input = { displayName: 'Guest', partySize: 1, locale: 'es' as const }
it('creates one persisted 256-bit identity across concurrent calls and restores it after reload', async () => {
  const api = await import('./installation')
  const [a, b] = await Promise.all([api.installationSecret(), api.installationSecret()])
  expect(a).toMatch(/^[a-f0-9]{64}$/)
  expect(a).toBe(b)
  expect(mock.write).toHaveBeenCalledTimes(1)
  mock.read.mockResolvedValue({ value: mock.write.mock.calls[0]![0].value })
  vi.resetModules()
  expect(await (await import('./installation')).installationSecret()).toBe(a)
})
it('fails closed when storage fails or is corrupt, without replacing the saved identity', async () => {
  mock.read.mockResolvedValue({ value: '{broken' })
  await expect((await import('./installation')).installationSecret()).rejects.toThrow()
  expect(mock.write).not.toHaveBeenCalled()
  vi.resetModules()
  mock.read.mockResolvedValue({ value: null })
  mock.write.mockRejectedValue(new Error('locked'))
  await expect((await import('./installation')).installationSecret()).rejects.toThrow('locked')
})
it('persists and reuses intent before HTTP, including reload; only clears after success', async () => {
  const api = await import('./installation'), key = crypto.randomUUID()
  const first = await api.prepareMobileJoin('q', key, input)
  const again = await api.prepareMobileJoin('q', crypto.randomUUID(), input)
  expect(first.key).toBe(key); expect(again.key).toBe(key)
  mock.read.mockResolvedValue({ value: mock.write.mock.calls.at(-1)![0].value })
  vi.resetModules()
  const reloaded = await import('./installation')
  expect((await reloaded.prepareMobileJoin('q', crypto.randomUUID(), input)).key).toBe(key)
  await reloaded.finishMobileJoin(key)
  const next = crypto.randomUUID()
  expect((await reloaded.prepareMobileJoin('q', next, input)).key).toBe(next)
})
it('serializes concurrent intent writes and rejects contact-bearing payloads', async () => {
  const api = await import('./installation')
  await Promise.all([api.prepareMobileJoin('q1', crypto.randomUUID(), input), api.prepareMobileJoin('q2', crypto.randomUUID(), input)])
  expect(JSON.parse(mock.write.mock.calls.at(-1)![0].value).pending).toHaveLength(2)
  await expect(api.prepareMobileJoin('q3', crypto.randomUUID(), { ...input, whatsapp: { consent: false } } as typeof input)).rejects.toThrow()
})
